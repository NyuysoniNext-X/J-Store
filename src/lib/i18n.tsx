const Ctx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string, values?: Record<string, string | number>) => string;
}>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const stored = localStorage.getItem("jstore.lang");
    if (stored === "en" || stored === "fr") setLangState(stored);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("jstore.lang", l);
  }, []);
  const t = (k: string, values?: Record<string, string | number>) => {
    const entry = dict[k];
    if (entry) {
      return entry[lang].replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
        values?.[name] === undefined ? match : String(values[name]),
      );
    }
    if (import.meta.env.DEV) console.warn(`Missing ${lang} translation: "${k}"`);
    return k;
  };
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
